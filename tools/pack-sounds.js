// Packs the sound files in assets/sounds/cap/ into assets/sounds/cap-sounds.js, a plain
// script that the page loads with a <script> tag. The game decodes the sounds from it into
// memory, so nothing has to be fetched (which browsers block when index.html is opened
// straight from disk).
//
// Run after adding or changing a sound:  npm run sounds

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'assets', 'sounds', 'cap');
const out = path.join(__dirname, '..', 'assets', 'sounds', 'cap-sounds.js');

const files = [];
const walk = (dir) => fs.readdirSync(dir).sort().forEach(name => {
    const full = path.join(dir, name);
    if(fs.statSync(full).isDirectory()) walk(full);
    else if(/\.(mp3|wav)$/i.test(name)) files.push(full);
});
walk(root);

const lines = files.map(file => {
    const key = path.relative(root, file).split(path.sep).join('/');
    return '  ' + JSON.stringify(key) + ': ' + JSON.stringify(fs.readFileSync(file).toString('base64'));
});
fs.writeFileSync(out,
    '// Generated by tools/pack-sounds.js from assets/sounds/cap/ (see CREDITS.txt there). Do not edit.\n' +
    'window.CAP_SOUNDS = {\n' + lines.join(',\n') + '\n};\n');
console.log('Packed ' + files.length + ' sounds into ' + path.relative(process.cwd(), out) +
    ' (' + Math.round(fs.statSync(out).size / 1024) + ' KB)');
